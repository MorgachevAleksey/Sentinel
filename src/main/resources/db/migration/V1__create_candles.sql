CREATE TABLE candles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker VARCHAR(20) NOT NULL,
    timeframe VARCHAR(16) NOT NULL,
    open_time TIMESTAMPTZ NOT NULL,

    open_price NUMERIC(19, 6) NOT NULL,
    high_price NUMERIC(19, 6) NOT NULL,
    low_price NUMERIC(19, 6) NOT NULL,
    close_price NUMERIC(19, 6) NOT NULL,

    volume NUMERIC(24, 6) NOT NULL,

    CONSTRAINT uq_candles_ticker_timeframe_open_time
    UNIQUE (ticker, timeframe, open_time),

    CONSTRAINT chk_candles_prices
    CHECK (
        low_price > 0
        AND low_price <= open_price
        AND open_price <= high_price
        AND low_price <= close_price
        AND close_price <= high_price
    ),

    CONSTRAINT chk_candles_volume_nonnegative
        CHECK (volume >= 0)
);